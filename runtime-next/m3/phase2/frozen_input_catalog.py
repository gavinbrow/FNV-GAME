"""Bounded build-input inventory, with explicit access to known local state files.

Never enumerates FNV/work or FNV/local recursively. Seeds regenerated by the
build are archived separately rather than incorrectly treated as immutable.
"""
import argparse
import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[2]


def collect(project):
    runtime = project / 'runtime-next'
    static = [runtime / p for p in (
        'build-v7/ehvariants_w2.json', 'build-v7/sg_sidecar_w2.json',
        'build-v7/callee_fixups.json', 'reloc-v7/binding_overlay.json',
        'reloc-v7/int_constants.json', 'reloc-v5/tail_alias_candidates.json',
        'coverage-v3/extra_pieces.json', 'link-v2/extra_labels.json',
        'direct-v1/iat_spec.json')]
    local = Path(os.environ.get('FNV_LT_DIR') or project / 'FNV/local/mcp/local-targets')
    static += [local / p for p in ('state.json', 'catalog.json', 'symbols.json')]
    static.append(project / 'FNV/scripts/local_targets.py')
    state = json.loads((local / 'state.json').read_bytes())
    contributions = Path(os.environ.get('FNV_CONTRIB_DIR') or project / 'FNV/contributions')
    for address in state.get('accepted', {}):
        if len(address) != 10 or not address.startswith('0x'):
            raise ValueError('invalid accepted contribution address')
        int(address[2:], 16)
        static.append(contributions / ('FUN_' + address[2:] + '.cpp'))
    variants = runtime / 'build-v7/ehvariants_w2.json'
    if variants.is_file():
        for entry in json.loads(variants.read_bytes()):
            path = (variants.parent / entry['obj']).resolve()
            if not path.is_relative_to(runtime.resolve()):
                raise ValueError('EH variant object escapes runtime tree')
            static.append(path)
    tools = project / 'FNV/tools'
    roots = [Path(os.environ.get(key) or tools / default) for key, default in (
        ('FNV_MSVC9_ROOT', 'vc2008'), ('FNV_MSVC9_RTM_ROOT', 'vc2008rtm'), ('FNV_MSVC8_ROOT', 'vc8sp1'))]
    for root in roots:
        vc = root / 'VC' if (root / 'VC/bin/cl.exe').is_file() else root
        if not (vc / 'bin/cl.exe').is_file():
            raise ValueError('expected compiler root unavailable')
        static.extend(p for p in (vc / 'bin').iterdir() if p.is_file() and p.suffix.lower() in ('.dll', '.exe'))
        for include in (vc / 'include', root / 'SDK/Include', root / 'SDK/include', vc / 'PlatformSDK/Include'):
            if include.is_dir():
                static.extend(p for p in include.rglob('*') if p.is_file())
        for name in ('libcmt.lib', 'libcpmt.lib'):
            if (vc / 'lib' / name).is_file():
                static.append(vc / 'lib' / name)
    unique = sorted({p.resolve() for p in static})
    seeds = [runtime / 'data-v3/symbolic.json', runtime / 'data-v3/out/manifest.json']
    return dict(schema_version=1, scope='Known source/recipe/static metadata/toolchain dependencies and accepted contribution sources; not an assertion of complete OS/environment dependency closure.',
                watch=[str(p) for p in unique if p.is_file()],
                optional_absent=[str(p) for p in unique if not p.exists()],
                generated_seeds=[str(p.resolve()) for p in seeds if p.is_file()])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    result = collect(PROJECT)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open('x', encoding='utf-8') as stream:
        json.dump(result, stream, indent=2)
    print(json.dumps({key: len(result[key]) for key in ('watch', 'optional_absent', 'generated_seeds')}))


if __name__ == '__main__':
    main()
