r"""M3 phase 1: the generated globals as pseudo-unit 200000 for data-v1 place.py (modelled on data-v2\libsecs.py). Same record format as phase0.work().
Each global is one section record (name '.data' / '.rdata', no relocations in phase 1) with a forced address: tier M = placement by the manifest address
(verified against the reference bytes by place.py before it is accepted), independent of byte uniqueness. Symbol names are prefixed 'm3$' so no extern
of the existing sources resolves through them (data-v1 counters change only by the generated bytes)."""
import os, sys
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import splice
UID = 200000
ALIGN = {1: 0x00100000, 2: 0x00200000, 4: 0x00300000, 8: 0x00400000, 16: 0x00500000}      # IMAGE_SCN_ALIGN_1/2/4/8/16BYTES
FLAGS = {'.data': 0xC0000040, '.rdata': 0x40000040}


def m3_units():
    secs = []
    for k, r in enumerate(splice.load()):
        e = r['entry']; sym = 'm3$' + e['name']
        # phase 1b: pointer fields as DIR32 relocation records with the result pre-resolved (rsrc 'm3', rexp = target VA + addend), so tier-M verify and the report
        # count the field value; the section index tsec is 0 (extern-style), so no other resolver path touches them
        rl = [(off, 6, nm, 0, 0, 2, add, 'm3', (tva + add) & 0xffffffff) for (off, nm, add), tva in zip(r['relocs'], r['reloc_va'])]
        secs.append(dict(u=UID, k=k, name=e['section'], flags=FLAGS[e['section']] | ALIGN[e.get('align') or e['size']], data=r['data'], size=len(r['data']), relocs=rl,
                         defs=[(sym, 0, 2)], hints=[(e['va'], 'm3-name', sym)], forced=e['va'], kind0='m3-global'))
    return {UID: dict(idx=UID, secs=secs, err=None)}
